@dataclass(frozen=True)
class Finding:
    tool: str
    path: str
    line: int
    column: int
    code: str
    message: str
    severity: str = "error"
    fixable: bool = False


@dataclass
class ToolResult:
    name: str
    status: str
    version: str = ""
    files: int = 0
    findings: list[Finding] = field(default_factory=list)
    error: str | None = None
    duration_s: float = 0.0
    changed: list[str] = field(default_factory=list)


@dataclass
class Discovery:
    python: list[Path] = field(default_factory=list)
    c: list[Path] = field(default_factory=list)
    generated: int = 0
    excluded: int = 0


def _relative(path: Path) -> Path | None:
    try:
        return path.resolve().relative_to(REPO_ROOT)
    except (OSError, ValueError):
        return None


def rel_path(path: Path) -> str:
    relative = _relative(path)
    if relative is None:
        return path.as_posix()
    return relative.as_posix()


def is_excluded(relative: Path) -> bool:
    parts = relative.parts
    if not parts:
        return False
    if any(part in EXCLUDED_DIR_NAMES for part in parts[:-1]):
        return True
    posix = relative.as_posix()
    if posix in EXCLUDED_FILES:
        return True
    for prefix in EXCLUDED_PREFIXES:
        if posix == prefix or posix.startswith(prefix + "/"):
            return True
    return False


def is_generated(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            head = [handle.readline() for _ in range(40)]
    except OSError:
        return False
    return bool(GENERATED_MARKERS.search("".join(head)))


def _walk(root: Path, suffixes: frozenset[str], stats: dict) -> list[Path]:
    found: list[Path] = []
    if not root.is_dir():
        return found
    for dirpath, dirnames, filenames in os.walk(root):
        current = Path(dirpath)
        kept: list[str] = []
        for name in dirnames:
            relative = _relative(current / name)
            if name in EXCLUDED_DIR_NAMES or relative is None:
                stats["excluded"] += 1
                continue
            if is_excluded(relative):
                stats["excluded"] += 1
                continue
            kept.append(name)
        dirnames[:] = kept
        for name in filenames:
            if Path(name).suffix.lower() not in suffixes:
                continue
            path = current / name
            relative = _relative(path)
            if relative is None or is_excluded(relative):
                stats["excluded"] += 1
                continue
            found.append(path)
    return found


def _explicit_files(
    values: Sequence[str], stats: dict, diagnostics: list[str]
) -> list[Path]:
    found: list[Path] = []
    for value in values:
        path = Path(value)
        if not path.is_absolute():
            path = (Path.cwd() / path).resolve()
        if path.is_dir():
            found.extend(_walk(path, ALL_SUFFIXES, stats))
            continue
        if not path.is_file():
            diagnostics.append("skip missing path: %s" % value)
            continue
        relative = _relative(path)
        if relative is None:
            diagnostics.append("skip path outside the repository: %s" % value)
            continue
        if is_excluded(relative):
            diagnostics.append("skip excluded path: %s" % value)
            stats["excluded"] += 1
            continue
        found.append(path)
    return found


def discover(
    values: Sequence[str] | None, diagnostics: list[str]
) -> Discovery:
    stats = {"excluded": 0}
    if values:
        candidates = _explicit_files(values, stats, diagnostics)
    else:
        candidates = []
        for root in PYTHON_ROOTS:
            candidates.extend(_walk(REPO_ROOT / root, PYTHON_SUFFIXES, stats))
        for root in C_ROOTS:
            candidates.extend(_walk(REPO_ROOT / root, C_SUFFIXES, stats))
    unique = list(dict.fromkeys(candidates))
    unique.sort(key=rel_path)
    result = Discovery(excluded=stats["excluded"])
    for path in unique:
        suffix = path.suffix.lower()
        if suffix in PYTHON_SUFFIXES:
            result.python.append(path)
        elif suffix in C_SUFFIXES:
            if is_generated(path):
                result.generated += 1
                if values:
                    diagnostics.append(
                        "skip generated file: %s" % rel_path(path)
                    )
                continue
            result.c.append(path)
    return result


def default_lvgl_version() -> str:
    override = os.environ.get("LVGL_VERIFY_LOOP_LVGL_VERSION")
    if override:
        return override
    meta = REPO_ROOT / "scripts" / "meta" / "versions.json"
    try:
        payload = json.loads(meta.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return DEFAULT_LVGL
    value = payload.get("default")
    if isinstance(value, str) and value:
        return value
    return DEFAULT_LVGL


def _is_lvgl_8(version: str) -> bool:
    head = version.split(".", 1)[0]
    return head.isdigit() and int(head) <= 8


def _scripts_dirs() -> list[Path]:
    dirs: list[Path] = []
    scripts = ""
    try:
        import sysconfig

        for scheme in ("nt_user", "posix_user", "osx_framework_user"):
            try:
                path = sysconfig.get_path("scripts", scheme=scheme)
            except KeyError:
                continue
            if path:
                dirs.append(Path(path))
        scripts = sysconfig.get_path("scripts")
    except Exception:  # noqa: BLE001 - optional discovery helper
        scripts = ""
    if scripts:
        dirs.append(Path(scripts))
    try:
        import site

        user_base = site.getuserbase()
    except Exception:  # noqa: BLE001 - optional discovery helper
        user_base = ""
    if user_base:
        dirs.append(Path(user_base) / "bin")
        dirs.append(Path(user_base) / "Scripts")
    unique: list[Path] = []
    for directory in dirs:
        if directory not in unique:
            unique.append(directory)
    return unique


def resolve_tool(name: str) -> list[str] | None:
    override = os.environ.get(TOOL_ENV_VARS[name])
    if override:
        return [override]
    found = shutil.which(name)
    if found:
        return [found]
    suffixes = [".exe", ""] if os.name == "nt" else [""]
    for directory in _scripts_dirs():
        for suffix in suffixes:
            candidate = directory / (name + suffix)
            if candidate.is_file():
                return [str(candidate)]
    if name == "ruff":
        return [sys.executable, "-m", "ruff"]
    return None


def tool_version(command: Sequence[str]) -> str:
    try:
        proc = subprocess.run(
            list(command) + ["--version"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=20,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    first = _first_line(proc.stdout)
    return first


def run_command(
    command: Sequence[str], timeout: float
) -> subprocess.CompletedProcess:
    return subprocess.run(
        list(command),
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
    )


def _first_line(text: str | None) -> str:
    for line in (text or "").splitlines():
        line = line.strip()
        if line:
            return line
    return ""


def _batches(items: Sequence[Path], size: int = BATCH_SIZE) -> Iterable:
    for index in range(0, len(items), size):
        yield items[index : index + size]


def _missing(name: str, skip_missing: bool, hint: str) -> ToolResult:
    status = "skipped" if skip_missing else "error"
    return ToolResult(name=name, status=status, error="not found: " + hint)


def _tool_paths(files: Sequence[Path]) -> list[str]:
    return [str(path) for path in files]


def _digest(path: Path) -> str:
    try:
        return hashlib.sha1(path.read_bytes()).hexdigest()
    except OSError:
        return ""


def _changed_files(
    before: dict[Path, str], files: Sequence[Path]
) -> list[str]:
    return [
        rel_path(path) for path in files if before.get(path) != _digest(path)
    ]


def _comment_spans_c(text: str) -> list[tuple[str, int, int, int]]:
    spans: list[tuple[str, int, int, int]] = []
    index = 0
    length = len(text)
    line = 1
    column = 0
    while index < length:
        char = text[index]
        if char == "\n":
            line += 1
            column = 0
            index += 1
            continue
        if char == '"' or char == "'":
            quote = char
            index += 1
            column += 1
            while index < length and text[index] != quote:
                if text[index] == "\\":
                    index += 1
                    column += 1
                if index < length and text[index] == "\n":
                    line += 1
                    column = 0
                index += 1
                column += 1
            index += 1
            column += 1
            continue
        if text.startswith("//", index):
            start_line, start_col = line, column
            while index < length and text[index] != "\n":
                index += 1
                column += 1
            spans.append(("COMMENT", start_line, start_col, start_line))
            continue
        if text.startswith("/*", index):
            start_line, start_col = line, column
            index += 2
            column += 2
            while index < length and not text.startswith("*/", index):
                if text[index] == "\n":
                    line += 1
                    column = 0
                else:
                    column += 1
                index += 1
            index += 2
            column += 2
            spans.append(("COMMENT", start_line, start_col, line))
            continue
        index += 1
        column += 1
    return spans


def _docstring_nodes(tree: ast.AST) -> list[ast.Constant]:
    nodes: list[ast.Constant] = []
    owners = (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
    for node in ast.walk(tree):
        if not isinstance(node, owners):
            continue
        body = node.body
        if not body:
            continue
        first = body[0]
        if not isinstance(first, ast.Expr):
            continue
        value = first.value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            nodes.append(value)
    return nodes


def _comment_spans_python(text: str) -> list[tuple[str, int, int, int]]:
    spans: list[tuple[str, int, int, int]] = []
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return spans
    for token in tokens:
        if token.type != tokenize.COMMENT:
            continue
        spans.append(("COMMENT", token.start[0], token.start[1], token.end[0]))
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return spans
    for node in _docstring_nodes(tree):
        start = getattr(node, "lineno", 1)
        end = getattr(node, "end_lineno", start)
        spans.append(("DOCSTRING", start, 0, end))
    return spans


def _comment_exempt(lines: Sequence[str], start: int, end: int) -> bool:
    for line in range(start, min(end, len(lines)) + 1):
        content = lines[line - 1]
        if line == 1 and content.lstrip().startswith("#!"):
            return True
        if any(marker in content for marker in EXEMPT_COMMENT_MARKERS):
            return True
    return False


def _scan_comments(path: Path) -> list[Finding]:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    if path.suffix.lower() in PYTHON_SUFFIXES:
        spans = _comment_spans_python(text)
    else:
        spans = _comment_spans_c(text)
    lines = text.splitlines()
    findings: list[Finding] = []
    for code, start, start_col, end in spans:
        if _comment_exempt(lines, start, end):
            continue
        findings.append(
            Finding(
                tool="comments",
                path=rel_path(path),
                line=start,
                column=start_col + 1,
                code=code,
                message=(
                    "docstring is not allowed"
                    if code == "DOCSTRING"
                    else "comment is not allowed"
                ),
            )
        )
    return findings


def run_comment_check(files: Sequence[Path]) -> ToolResult:
    started = time.monotonic()
    findings: list[Finding] = []
    for path in files:
        findings.extend(_scan_comments(path))
    return ToolResult(
        name="comments",
        status="findings" if findings else "ok",
        files=len(files),
        findings=findings,
        duration_s=time.monotonic() - started,
    )


def _parse_ruff(payload: Iterable[dict]) -> list[Finding]:
    findings: list[Finding] = []
    for item in payload:
        if not isinstance(item, dict):
            continue
        location = item.get("location") or {}
        findings.append(
            Finding(
                tool="ruff",
                path=rel_path(Path(str(item.get("filename") or ""))),
                line=int(location.get("row") or 0),
                column=int(location.get("column") or 0),
                code=str(item.get("code") or ""),
                message=str(item.get("message") or ""),
                fixable=bool(item.get("fix")),
            )
        )
    return findings


def _ruff_command(
    command: Sequence[str], subcommand: str, *extra: str
) -> list[str]:
    return list(command) + [
        subcommand,
        "--force-exclude",
        "--config",
        str(REPO_ROOT / "pyproject.toml"),
        *extra,
    ]


def run_ruff_check(
    files: Sequence[Path], *, skip_missing: bool, timeout: float
) -> ToolResult:
    command = resolve_tool("ruff")
    if command is None:
        return _missing("ruff", skip_missing, RUFF_COMMENT)
    version = tool_version(command)
    if not files:
        return ToolResult(name="ruff", status="ok", version=version)
    started = time.monotonic()
    findings: list[Finding] = []
    error: str | None = None
    for batch in _batches(files):
        argv = _ruff_command(
            command,
            "check",
            "--no-fix",
            "--output-format=json",
            *_tool_paths(batch),
        )
        try:
            proc = run_command(argv, timeout)
        except subprocess.TimeoutExpired:
            error = "ruff check timed out"
            break
        except OSError as exc:
            error = "ruff check failed to start: %s" % exc
            break
        if proc.returncode not in (0, 1):
            error = _first_line(proc.stderr) or (
                "ruff check exited %d" % proc.returncode
            )
            break
        try:
            payload = json.loads(proc.stdout or "[]")
        except ValueError:
            error = "ruff check returned invalid JSON"
            break
        if not isinstance(payload, list):
            error = "ruff check returned an unexpected JSON shape"
            break
        findings.extend(_parse_ruff(payload))
    duration = time.monotonic() - started
    if error:
        return ToolResult(
            name="ruff",
            status="error",
            version=version,
            files=len(files),
            error=error,
            duration_s=duration,
        )
    return ToolResult(
        name="ruff",
        status="findings" if findings else "ok",
        version=version,
        files=len(files),
        findings=findings,
        duration_s=duration,
    )


def run_ruff_format(
    files: Sequence[Path],
    *,
    write: bool,
    skip_missing: bool,
    timeout: float,
) -> ToolResult:
    command = resolve_tool("ruff")
    if command is None:
        return _missing("ruff", skip_missing, RUFF_COMMENT)
    version = tool_version(command)
    if not files:
        return ToolResult(name="ruff-format", status="ok", version=version)
    started = time.monotonic()
    before = {path: _digest(path) for path in files} if write else {}
    findings: list[Finding] = []
    error: str | None = None
    for batch in _batches(files):
        extra = ["--check"] if not write else []
        argv = _ruff_command(
            command,
            "format",
            *extra,
            *_tool_paths(batch),
        )
        try:
            proc = run_command(argv, timeout)
        except subprocess.TimeoutExpired:
            error = "ruff format timed out"
            break
        except OSError as exc:
            error = "ruff format failed to start: %s" % exc
            break
        if proc.returncode not in (0, 1):
            error = _first_line(proc.stderr) or (
                "ruff format exited %d" % proc.returncode
            )
            break
        if not write:
            for line in proc.stdout.splitlines():
                if not line.startswith(RUFF_WOULD_REFORMAT):
                    continue
                target = line[len(RUFF_WOULD_REFORMAT) :].strip()
                findings.append(
                    Finding(
                        tool="ruff-format",
                        path=rel_path(Path(target)),
                        line=1,
                        column=1,
                        code="FORMAT",
                        message="would be reformatted by ruff format",
                        severity="warning",
                        fixable=True,
                    )
                )
    duration = time.monotonic() - started
    changed = _changed_files(before, files) if write and not error else []
    if error:
        return ToolResult(
            name="ruff-format",
            status="error",
            version=version,
            files=len(files),
            error=error,
            duration_s=duration,
        )
    return ToolResult(
        name="ruff-format",
        status="findings" if findings else "ok",
        version=version,
        files=len(files),
        findings=findings,
        duration_s=duration,
        changed=changed,
    )


def _parse_clang_format(stderr: str) -> list[Finding]:
    findings: list[Finding] = []
    for line in stderr.splitlines():
        match = CLANG_FORMAT_LINE.match(line.strip())
        if not match:
            continue
        findings.append(
            Finding(
                tool="clang-format",
                path=rel_path(Path(match.group("path"))),
                line=int(match.group("line")),
                column=int(match.group("column")),
                code="FORMAT",
                message=match.group("message").strip()
                or "code should be clang-formatted",
                severity="warning",
                fixable=True,
            )
        )
    return findings


def run_clang_format(
    files: Sequence[Path],
    *,
    write: bool,
    skip_missing: bool,
    timeout: float,
) -> ToolResult:
    command = resolve_tool("clang-format")
    if command is None:
        return _missing("clang-format", skip_missing, CLANG_FORMAT_COMMENT)
    version = tool_version(command)
    if not files:
        return ToolResult(name="clang-format", status="ok", version=version)
    started = time.monotonic()
    before = {path: _digest(path) for path in files} if write else {}
    findings: list[Finding] = []
    error: str | None = None
    for batch in _batches(files):
        argv = list(command)
        if write:
            argv.append("-i")
        else:
            argv.extend(["--dry-run", "--Werror"])
        argv.append("--style=file")
        argv.extend(_tool_paths(batch))
        try:
            proc = run_command(argv, timeout)
        except subprocess.TimeoutExpired:
            error = "clang-format timed out"
            break
        except OSError as exc:
            error = "clang-format failed to start: %s" % exc
            break
        if proc.returncode not in (0, 1):
            error = _first_line(proc.stderr) or (
                "clang-format exited %d" % proc.returncode
            )
            break
        if not write:
            parsed = _parse_clang_format(proc.stderr)
            if not parsed and proc.returncode:
                error = "clang-format reported a violation it did not parse"
                break
            findings.extend(parsed)
    duration = time.monotonic() - started
    changed = _changed_files(before, files) if write and not error else []
    if error:
        return ToolResult(
            name="clang-format",
            status="error",
            version=version,
            files=len(files),
            error=error,
            duration_s=duration,
        )
    return ToolResult(
        name="clang-format",
        status="findings" if findings else "ok",
        version=version,
        files=len(files),
        findings=findings,
        duration_s=duration,
        changed=changed,
    )


def _cppcheck_prerequisites(version: str) -> list[str]:
    missing: list[str] = []
    lvgl = REPO_ROOT / "engine" / "lvgl" / version
    sdk = REPO_ROOT / "dist" / "lvgl" / version / "include"
    if not lvgl.is_dir():
        missing.append(str(lvgl))
    if not sdk.is_dir():
        missing.append(str(sdk))
    return missing


def _cppcheck_includes(version: str) -> list[Path]:
    lvgl = REPO_ROOT / "engine" / "lvgl" / version
    sdk = REPO_ROOT / "dist" / "lvgl" / version / "include"
    if _is_lvgl_8(version):
        lodepng = lvgl / "src" / "extra" / "libs" / "png"
    else:
        lodepng = lvgl / "src" / "libs" / "lodepng"
    dirs = [REPO_ROOT / "engine", lvgl]
    if lodepng.is_dir():
        dirs.append(lodepng)
    dirs.append(sdk)
    return dirs


def _cppcheck_argv(
    command: Sequence[str],
    files: Sequence[Path],
    version: str,
    misra: bool,
) -> list[str]:
    argv = list(command) + [
        "--quiet",
        "--std=c11",
        "--platform=win64",
        "--enable=warning,performance,portability",
        "--inline-suppr",
        "--suppress=missingIncludeSystem",
        "--error-exitcode=7",
        "--relative-paths=%s" % REPO_ROOT,
        "--template={file}|{line}|{column}|{severity}|{id}|{message}",
    ]
    suppressions = REPO_ROOT / ".cppcheck-suppressions"
    if suppressions.is_file():
        argv.append("--suppressions-list=%s" % suppressions)
    if misra:
        argv.append("--addon=misra")
        argv.append("--addon-python=%s" % sys.executable)
    for directory in _cppcheck_includes(version):
        argv.extend(["-I", str(directory)])
    argv.append("-DLV_CONF_INCLUDE_SIMPLE")
    argv.append("-DLV_LVGL_H_INCLUDE_SIMPLE")
    argv.append("-D_WIN32")
    if _is_lvgl_8(version):
        argv.append("-DLVGL_MAJOR_8=1")
    argv.extend(_tool_paths(files))
    return argv


def _parse_cppcheck(stderr: str) -> list[Finding]:
    findings: list[Finding] = []
    for line in stderr.splitlines():
        match = CPPCHECK_LINE.match(line.strip())
        if not match:
            continue
        path = match.group("path").replace("\\", "/")
        findings.append(
            Finding(
                tool="cppcheck",
                path=rel_path(Path(path)),
                line=int(match.group("line")),
                column=int(match.group("column")),
                code=match.group("code").strip() or "cppcheck",
                message=match.group("message").strip(),
                severity=match.group("severity").strip() or "warning",
            )
        )
    return findings


def run_cppcheck(
    files: Sequence[Path],
    *,
    version: str,
    misra: bool,
    skip_missing: bool,
    timeout: float,
    diagnostics: list[str],
) -> ToolResult:
    command = resolve_tool("cppcheck")
    if command is None:
        return _missing("cppcheck", skip_missing, CPPCHECK_COMMENT)
    version_text = tool_version(command)
    if not files:
        return ToolResult(
            name="cppcheck", status="skipped", version=version_text
        )
    missing = _cppcheck_prerequisites(version)
    if missing:
        message = "missing LVGL/SDK tree for %s: %s" % (
            version,
            ", ".join(missing),
        )
        diagnostics.append(message)
        if skip_missing:
            return ToolResult(
                name="cppcheck",
                status="skipped",
                version=version_text,
                error=message,
            )
        return ToolResult(
            name="cppcheck",
            status="error",
            version=version_text,
            error=message,
        )
    started = time.monotonic()
    findings: list[Finding] = []
    error: str | None = None
    for batch in _batches(files, 50):
        argv = _cppcheck_argv(command, batch, version, misra)
        try:
            proc = run_command(argv, timeout)
        except subprocess.TimeoutExpired:
            error = "cppcheck timed out"
            break
        except OSError as exc:
            error = "cppcheck failed to start: %s" % exc
            break
        if proc.returncode not in (0, 7):
            error = _first_line(proc.stderr) or (
                "cppcheck exited %d" % proc.returncode
            )
            break
        for finding in _parse_cppcheck(proc.stderr):
            if not _is_vendored_path(finding.path):
                findings.append(finding)
    duration = time.monotonic() - started
    if error:
        return ToolResult(
            name="cppcheck",
            status="error",
            version=version_text,
            files=len(files),
            error=error,
            duration_s=duration,
        )
    return ToolResult(
        name="cppcheck",
        status="findings" if findings else "ok",
        version=version_text,
        files=len(files),
        findings=findings,
        duration_s=duration,
    )


def _is_vendored_path(path: str) -> bool:
    candidate = Path(path)
    try:
        relative = candidate.relative_to(REPO_ROOT)
    except ValueError:
        relative = candidate
    posix = relative.as_posix()
    return posix.startswith(("engine/lvgl/", "engine/third_party/", "dist/"))


def parse_tools(value: str, *, allow_cppcheck: bool) -> list[str] | None:
    if value in (None, "", "all"):
        names = (
            list(TOOL_NAMES) if allow_cppcheck else ["ruff", "clang-format"]
        )
    else:
        names = [item.strip() for item in value.split(",") if item.strip()]
    if not allow_cppcheck and "cppcheck" in names:
        return None
    if any(name not in TOOL_NAMES for name in names):
        return None
    return names


def _filter_adapters(
    files: Sequence[Path], version: str, diagnostics: list[str]
) -> list[Path]:
    is_8 = _is_lvgl_8(version)
    kept: list[Path] = []
    for path in files:
        name = path.name
        if name == "adapter_8x.c" and not is_8:
            diagnostics.append(
                "cppcheck: skip %s for lvgl %s" % (rel_path(path), version)
            )
            continue
        if name == "adapter_9x.c" and is_8:
            diagnostics.append(
                "cppcheck: skip %s for lvgl %s" % (rel_path(path), version)
            )
            continue
        kept.append(path)
    return kept


def _cppcheck_targets(
    explicit: Sequence[Path] | None,
    discovery: Discovery,
    *,
    version: str,
    user_app: bool,
    diagnostics: list[str],
) -> list[Path]:
    if explicit:
        candidates = [
            path for path in discovery.c if path.suffix.lower() == ".c"
        ]
    else:
        candidates = _engine_c_sources()
        if user_app:
            candidates = list(candidates) + [
                path
                for path in discovery.c
                if rel_path(path).startswith("user/app/")
            ]
    candidates = [path for path in candidates if not is_generated(path)]
    return _filter_adapters(candidates, version, diagnostics)


def _engine_c_sources() -> list[Path]:
    engine = REPO_ROOT / "engine"
    paths = [
        path
        for sub in ("core", "render", "adapter")
        for path in (engine / sub).glob("*.c")
    ]
    return sorted(paths)


def _engine_cppcheck_files(version: str) -> list[Path]:
    candidates = _engine_c_sources()
    candidates = [path for path in candidates if not is_generated(path)]
    return _filter_adapters(candidates, version, [])


def _summary(findings: Sequence[Finding]) -> dict:
    by_tool: dict[str, int] = {}
    for finding in findings:
        by_tool[finding.tool] = by_tool.get(finding.tool, 0) + 1
    return {"total": len(findings), "by_tool": by_tool}


def build_report(
    *,
    command: str,
    results: Sequence[ToolResult],
    discovery: Discovery,
    diagnostics: Sequence[str],
    started: float,
    lvgl: str | None,
    changed: Sequence[str] | None = None,
) -> dict:
    findings: list[Finding] = []
    for result in results:
        findings.extend(result.findings)
    findings.sort(
        key=lambda item: (
            item.path,
            item.line,
            item.column,
            item.tool,
            item.code,
        )
    )
    has_error = any(result.status == "error" for result in results)
    report = {
        "schema": SCHEMA,
        "command": command,
        "ok": not findings and not has_error,
        "repo_root": REPO_ROOT.as_posix(),
        "lvgl": lvgl,
        "scripts": [
            {
                "name": result.name,
                "status": result.status,
                "version": result.version,
                "files": result.files,
                "findings": len(result.findings),
                "error": result.error,
                "duration_s": round(result.duration_s, 3),
            }
            for result in results
        ],
        "files": {
            "python": len(discovery.python),
            "c": len(discovery.c),
            "checked": len(discovery.python) + len(discovery.c),
            "skipped_generated": discovery.generated,
            "skipped_excluded": discovery.excluded,
        },
        "findings": [asdict(finding) for finding in findings],
        "summary": _summary(findings),
        "diagnostics": list(diagnostics),
        "duration_s": round(time.monotonic() - started, 3),
    }
    if changed is not None:
        report["changed"] = list(changed)
    return report


def render_text(report: dict) -> str:
    lines: list[str] = []
    for tool in report["scripts"]:
        detail = "%s: %s" % (tool["name"], tool["status"])
        if tool["files"]:
            detail += ", %d file(s)" % tool["files"]
        detail += ", %.2fs" % tool["duration_s"]
        if tool["error"]:
            detail += " (%s)" % tool["error"]
        lines.append(detail)
    for finding in report["findings"]:
        lines.append(
            "%(path)s:%(line)d:%(column)d: %(tool)s %(code)s: "
            "%(message)s" % finding
        )
    if "changed" in report:
        for path in report["changed"]:
            lines.append("reformatted: %s" % path)
    lines.append("%d finding(s)" % report["summary"]["total"])
    return "\n".join(lines)


def _emit_diagnostics(diagnostics: Sequence[str]) -> None:
    for line in diagnostics:
        sys.stderr.write("lint: %s\n" % line)


def _finish(report: dict, *, as_json: bool, code: int) -> int:
    _emit_diagnostics(report["diagnostics"])
    if as_json:
        sys.stdout.write(json.dumps(report, ensure_ascii=False, indent=2))
        sys.stdout.write("\n")
    else:
        sys.stdout.write(render_text(report) + "\n")
    return code


def cmd_check(args: argparse.Namespace) -> int:
    started = time.monotonic()
    diagnostics: list[str] = []
    tools = parse_tools(args.tools, allow_cppcheck=True)
    if tools is None:
        sys.stderr.write(
            "lint: --tools must be 'all' or a subset of %s\n"
            % ", ".join(TOOL_NAMES)
        )
        return 2
    discovery = discover(args.files, diagnostics)
    version = args.lvgl or default_lvgl_version()
    results: list[ToolResult] = []
    if "comments" in tools:
        results.append(
            run_comment_check(list(discovery.python) + list(discovery.c))
        )
    if "ruff" in tools:
        results.append(
            run_ruff_check(
                discovery.python,
                skip_missing=args.skip_missing,
                timeout=args.timeout,
            )
        )
    if "clang-format" in tools:
        results.append(
            run_clang_format(
                discovery.c,
                write=False,
                skip_missing=args.skip_missing,
                timeout=args.timeout,
            )
        )
    if "cppcheck" in tools:
        targets = _cppcheck_targets(
            args.files,
            discovery,
            version=version,
            user_app=args.cppcheck_user_app,
            diagnostics=diagnostics,
        )
        if not targets:
            diagnostics.append("cppcheck: no .c target files")
        results.append(
            run_cppcheck(
                targets,
                version=version,
                misra=args.misra,
                skip_missing=args.skip_missing,
                timeout=args.timeout,
                diagnostics=diagnostics,
            )
        )
    report = build_report(
        command="check",
        results=results,
        discovery=discovery,
        diagnostics=diagnostics,
        started=started,
        lvgl=version,
    )
    if any(result.status == "error" for result in results):
        return _finish(report, as_json=args.json, code=2)
    if report["findings"]:
        return _finish(report, as_json=args.json, code=1)
    return _finish(report, as_json=args.json, code=0)


def cmd_format(args: argparse.Namespace) -> int:
    started = time.monotonic()
    diagnostics: list[str] = []
    tools = parse_tools(args.tools, allow_cppcheck=False)
    if tools is None:
        sys.stderr.write(
            "lint: format supports 'all', 'ruff' or 'clang-format'\n"
        )
        return 2
    discovery = discover(args.files, diagnostics)
    results: list[ToolResult] = []
    if "ruff" in tools:
        results.append(
            run_ruff_format(
                discovery.python,
                write=not args.check,
                skip_missing=False,
                timeout=args.timeout,
            )
        )
    if "clang-format" in tools:
        results.append(
            run_clang_format(
                discovery.c,
                write=not args.check,
                skip_missing=False,
                timeout=args.timeout,
            )
        )
    changed: list[str] = []
    for result in results:
        changed.extend(result.changed)
    report = build_report(
        command="format",
        results=results,
        discovery=discovery,
        diagnostics=diagnostics,
        started=started,
        lvgl=None,
        changed=changed,
    )
    if any(result.status == "error" for result in results):
        return _finish(report, as_json=args.json, code=2)
    if args.check and report["findings"]:
        return _finish(report, as_json=args.json, code=1)
    return _finish(report, as_json=args.json, code=0)


def _hook_payload() -> dict | None:
    try:
        if sys.stdin.isatty():
            return None
    except (OSError, ValueError):
        pass
    try:
        raw = sys.stdin.buffer.read()
    except OSError:
        return None
    if not raw.strip():
        return None
    try:
        payload = json.loads(raw.decode("utf-8", "replace"))
    except ValueError:
        return None
    return payload if isinstance(payload, dict) else None


def _hook_path(payload: dict) -> Path | None:
    tool_input = payload.get("tool_input")
    if not isinstance(tool_input, dict):
        return None
    raw = tool_input.get("file_path")
    if not isinstance(raw, str) or not raw:
        return None
    path = Path(raw)
    if not path.is_absolute():
        cwd = payload.get("cwd")
        base = Path(cwd) if isinstance(cwd, str) and cwd else Path.cwd()
        path = base / path
    try:
        path = path.resolve()
    except OSError:
        return None
    return path


def _hook_findings(
    rel: Path, path: Path, diagnostics: list[str]
) -> list[Finding]:
    suffix = rel.suffix.lower()
    posix = rel.as_posix()
    findings: list[Finding] = []
    if suffix not in ALL_SUFFIXES:
        return findings
    findings.extend(run_comment_check([path]).findings)
    if suffix == ".py":
        check = run_ruff_check(
            [path], skip_missing=True, timeout=HOOK_TIMEOUT_S
        )
        findings.extend(check.findings)
        if check.status == "error":
            diagnostics.append(check.error or "ruff check failed")
        fmt = run_ruff_format(
            [path],
            write=False,
            skip_missing=True,
            timeout=HOOK_TIMEOUT_S,
        )
        findings.extend(fmt.findings)
        return findings
    if suffix not in C_SUFFIXES:
        return findings
    fmt = run_clang_format(
        [path], write=False, skip_missing=True, timeout=HOOK_TIMEOUT_S
    )
    findings.extend(fmt.findings)
    if fmt.status == "error":
        diagnostics.append(fmt.error or "clang-format failed")
    if posix.startswith("engine/"):
        if os.environ.get("LVGL_VERIFY_LOOP_LINT_HOOK_CPPCHECK", "1") == "0":
            return findings
        version = default_lvgl_version()
        targets = _engine_cppcheck_files(version)
        if suffix == ".c":
            if path in targets:
                targets = [path]
            else:
                return findings
        cpp = run_cppcheck(
            targets,
            version=version,
            misra=False,
            skip_missing=True,
            timeout=HOOK_TIMEOUT_S,
            diagnostics=diagnostics,
        )
        findings.extend(cpp.findings)
    return findings


def cmd_hook() -> int:
    if os.environ.get("LVGL_VERIFY_LOOP_LINT_HOOK", "1") == "0":
        return 0
    payload = _hook_payload()
    if payload is None:
        return 0
    path = _hook_path(payload)
    if path is None or not path.is_file():
        return 0
    rel = _relative(path)
    if rel is None or is_excluded(rel):
        return 0
    if path.suffix.lower() in C_SUFFIXES and is_generated(path):
        return 0
    diagnostics: list[str] = []
    try:
        findings = _hook_findings(rel, path, diagnostics)
    except (OSError, subprocess.SubprocessError) as exc:
        sys.stderr.write("lint hook: skipped (%s)\n" % exc)
        return 0
    for line in diagnostics:
        sys.stderr.write("lint hook: %s\n" % line)
    if not findings:
        return 0
    for finding in findings[:HOOK_MAX_FINDINGS]:
        message = finding.message.replace("\n", " ")
        if len(message) > HOOK_MESSAGE_LIMIT:
            message = message[: HOOK_MESSAGE_LIMIT - 3] + "..."
        sys.stderr.write(
            "%s:%d:%d: %s %s: %s\n"
            % (
                finding.path,
                finding.line,
                finding.column,
                finding.tool,
                finding.code,
                message,
            )
        )
    extra = len(findings) - HOOK_MAX_FINDINGS
    if extra > 0:
        sys.stderr.write("... %d more omitted\n" % extra)
    return 2


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="lint.py",
        description="Static checks and formatting for this repository.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    check = sub.add_parser("check", help="report findings without writing")
    check.add_argument("--json", action="store_true")
    check.add_argument("--tools", default="all")
    check.add_argument("--files", nargs="+", default=None)
    check.add_argument("--lvgl", default=None)
    check.add_argument("--cppcheck-user-app", action="store_true")
    check.add_argument("--misra", action="store_true")
    check.add_argument("--skip-missing", action="store_true")
    check.add_argument("--timeout", type=float, default=120.0)

    fmt = sub.add_parser("format", help="rewrite files in place")
    fmt.add_argument("--json", action="store_true")
    fmt.add_argument("--tools", default="all")
    fmt.add_argument("--files", nargs="+", default=None)
    fmt.add_argument("--check", action="store_true")
    fmt.add_argument("--timeout", type=float, default=120.0)

    sub.add_parser("hook", help="PostToolUse hook entry point")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.command == "hook":
        return cmd_hook()
    if args.command == "check":
        return cmd_check(args)
    return cmd_format(args)


if __name__ == "__main__":
    sys.exit(main())
