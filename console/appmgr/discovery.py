"""Directory-based app discovery and generated C registry.

An app is a directory under ``user/app`` that contains ``app.json``::

    {
      "entry": "xhs_page_create",
      "aliases": ["xhs"],
      "default": false
    }

The directory name is the app name; ``entry`` is the C function to call.
There is no central registry to edit.  Builds generate
``user/app/app_registry.inc`` from these files, and the fixed
``user/app/app.c`` entrypoint includes it.  Removing an app directory removes
it from the next build without touching any shared file.

``scan_apps`` is the tolerant view used by the management console; it returns
valid entries plus per-directory issues.  ``discover_apps`` is the strict view
used by builds and exporters: it raises :class:`DiscoveryError` instead of
silently skipping a malformed metadata file.
"""

from __future__ import annotations

import json
import os
import re
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import common

METADATA_NAME = "app.json"
REGISTRY_NAME = "app_registry.inc"
ENTRY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
REGISTRY_MARKER = (
    "/* Generated by console/appmgr/discovery.py; do not edit. */\n"
)


class DiscoveryError(RuntimeError):
    def __init__(
        self,
        code: str,
        message: str,
        *,
        path: Path | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.path = path


@dataclass(frozen=True)
class AppEntry:
    name: str
    entry: str
    aliases: tuple[str, ...]
    default: bool
    directory: Path


@dataclass(frozen=True)
class DiscoveryIssue:
    path: Path
    message: str


def app_directory(apps_dir: str | Path, name: str) -> Path:
    return Path(apps_dir) / name


def metadata_path(apps_dir: str | Path, name: str) -> Path:
    return app_directory(apps_dir, name) / METADATA_NAME


def registry_path(apps_dir: str | Path) -> Path:
    return Path(apps_dir) / REGISTRY_NAME


def scan_apps(
    apps_dir: str | Path,
) -> tuple[list[AppEntry], list[DiscoveryIssue]]:
    """Return metadata-declared apps and per-directory issues.

    Directories without ``app.json`` (for example ``user/app/demo``) are
    helpers, not apps, and are ignored.
    """

    root = Path(apps_dir)
    entries: list[AppEntry] = []
    issues: list[DiscoveryIssue] = []
    if not root.is_dir():
        issues.append(DiscoveryIssue(root, "app directory does not exist"))
        return entries, issues

    for path in sorted(root.iterdir()):
        if not path.is_dir() or path.is_symlink():
            continue
        metadata = path / METADATA_NAME
        if not metadata.is_file() or metadata.is_symlink():
            continue
        try:
            entry = _read_metadata(path)
        except DiscoveryError as exc:
            issues.append(DiscoveryIssue(metadata, str(exc)))
            continue
        entries.append(entry)
    return entries, issues


def discover_apps(apps_dir: str | Path) -> list[AppEntry]:
    """Strict discovery: fail on malformed metadata or duplicate identities."""

    entries, issues = scan_apps(apps_dir)
    if issues:
        first = issues[0]
        raise DiscoveryError(
            "app_metadata_invalid",
            f"{first.path}: {first.message}",
            path=first.path,
        )
    if not entries:
        raise DiscoveryError(
            "app_missing",
            f"no apps with {METADATA_NAME} found in {apps_dir}",
            path=Path(apps_dir),
        )
    entries = _ordered(entries)
    _validate_identities(entries)
    return entries


def default_app_name(apps_dir: str | Path) -> str | None:
    """Return the app explicitly marked ``"default": true``, if any."""

    entries, _issues = scan_apps(apps_dir)
    defaults = [entry for entry in entries if entry.default]
    return defaults[0].name if len(defaults) == 1 else None


def find_app(apps_dir: str | Path, name: str) -> AppEntry | None:
    for entry in discover_apps(apps_dir):
        if entry.name == name:
            return entry
    return None


def write_registry(apps_dir: str | Path) -> Path:
    """Write ``app_registry.inc`` only when its content changes."""

    root = Path(apps_dir)
    entries = discover_apps(root)
    data = render_registry(entries).encode("utf-8")
    target = registry_path(root)
    if target.is_file() and target.read_bytes() == data:
        return target
    fd, temp_name = tempfile.mkstemp(
        prefix=f".{REGISTRY_NAME}.", suffix=".tmp", dir=str(root)
    )
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(temp_name, target)
    except BaseException:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass
        raise
    return target


def render_registry(entries: list[AppEntry]) -> str:
    ordered = _ordered(entries)
    _validate_identities(ordered)
    lines = [
        REGISTRY_MARKER.rstrip("\n"),
        "#ifndef LVGL_VERIFY_LOOP_APP_REGISTRY_INC",
        "#define LVGL_VERIFY_LOOP_APP_REGISTRY_INC",
        "",
    ]
    for entry in ordered:
        lines.append(f"void {entry.entry}(void);")
    lines.extend(["", "static const app_entry_t apps[] = {"])
    for entry in ordered:
        lines.append(f'    {{"{entry.name}", {entry.entry}}},')
    lines.append("};")
    aliases = [
        (alias, entry.name)
        for entry in ordered
        for alias in entry.aliases
    ]
    lines.append("")
    lines.append(f"#define APP_ALIAS_COUNT {len(aliases)}")
    if aliases:
        lines.append("static const app_alias_t app_aliases[] = {")
        for alias, name in aliases:
            lines.append(f'    {{"{alias}", "{name}"}},')
        lines.append("};")
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def _read_metadata(directory: Path) -> AppEntry:
    name = directory.name
    if not common.NAME_RE.fullmatch(name):
        raise DiscoveryError(
            "app_metadata_invalid",
            f"app directory name {name!r} must match "
            "^[a-z][a-z0-9_]{0,31}$",
        )
    path = directory / METADATA_NAME
    try:
        payload: Any = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise DiscoveryError(
            "app_metadata_invalid", f"cannot read {METADATA_NAME}: {exc}"
        ) from exc
    if not isinstance(payload, dict):
        raise DiscoveryError(
            "app_metadata_invalid", f"{METADATA_NAME} must be an object"
        )
    entry = payload.get("entry")
    if not isinstance(entry, str) or not ENTRY_RE.fullmatch(entry):
        raise DiscoveryError(
            "app_metadata_invalid",
            f'{METADATA_NAME} entry must be a C identifier',
        )
    raw_aliases = payload.get("aliases", [])
    if raw_aliases is None:
        raw_aliases = []
    if not isinstance(raw_aliases, list):
        raise DiscoveryError(
            "app_metadata_invalid", f"{METADATA_NAME} aliases must be a list"
        )
    aliases: list[str] = []
    for value in raw_aliases:
        if (
            not isinstance(value, str)
            or not common.NAME_RE.fullmatch(value)
            or value == name
            or value in aliases
        ):
            raise DiscoveryError(
                "app_metadata_invalid",
                f"{METADATA_NAME} has an invalid alias {value!r}",
            )
        aliases.append(value)
    default = payload.get("default", False)
    if not isinstance(default, bool):
        raise DiscoveryError(
            "app_metadata_invalid", f"{METADATA_NAME} default must be boolean"
        )
    return AppEntry(
        name=name,
        entry=entry,
        aliases=tuple(aliases),
        default=default,
        directory=directory,
    )


def _ordered(entries: list[AppEntry]) -> list[AppEntry]:
    defaults = [entry for entry in entries if entry.default]
    if len(defaults) > 1:
        names = ", ".join(entry.name for entry in defaults)
        raise DiscoveryError(
            "app_default_conflict",
            f"more than one app is marked default: {names}",
        )
    default = defaults[0] if defaults else None
    if default is None and entries:
        default = sorted(entries, key=lambda item: item.name)[0]
    rest = sorted(
        (entry for entry in entries if entry is not default),
        key=lambda item: item.name,
    )
    return ([default] if default is not None else []) + rest


def _validate_identities(entries: list[AppEntry]) -> None:
    names = {entry.name for entry in entries}
    seen_aliases: dict[str, str] = {}
    for entry in entries:
        for alias in entry.aliases:
            if alias in names:
                raise DiscoveryError(
                    "app_alias_conflict",
                    f'alias "{alias}" collides with an app name',
                    path=entry.directory / METADATA_NAME,
                )
            owner = seen_aliases.get(alias)
            if owner is not None and owner != entry.name:
                raise DiscoveryError(
                    "app_alias_conflict",
                    f'alias "{alias}" is declared by {owner} and '
                    f"{entry.name}",
                    path=entry.directory / METADATA_NAME,
                )
            seen_aliases[alias] = entry.name
